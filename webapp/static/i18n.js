function detectInitialLang() {
  const tgCode = window.Telegram?.WebApp?.initDataUnsafe?.user?.language_code || "";
  if (tgCode && !tgCode.toLowerCase().startsWith("ru")) return "en";
  return "ru";
}

let currentUiLang = detectInitialLang();

function setUiLang(lang) {
  currentUiLang = lang === "en" ? "en" : "ru";
  document.documentElement.lang = currentUiLang;
  document.title = uiT("app_title");
}

function uiT(key, vars = null) {
  const dict = UI_STRINGS[currentUiLang] || UI_STRINGS.ru;
  let text = dict[key] ?? UI_STRINGS.ru[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}
